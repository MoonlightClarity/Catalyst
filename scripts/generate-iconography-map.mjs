import fs from "node:fs";
import path from "node:path";

const root = path.resolve(process.cwd());
const srcRoot = path.join(root, "src");
const symbolsPath = path.join(srcRoot, "ui", "CatalystSymbols.tsx");
const outputPath = path.join(root, "docs", "iconography-map.md");

const text = fs.readFileSync(symbolsPath, "utf8");
const componentTypes = [
  ["InstrumentGlyph", "InstrumentGlyphName", "name"],
  ["AnalyticalGlyph", "AnalyticalGlyphKind", "kind"],
  ["OutlineGlyph", "OutlineGlyphKind", "kind"],
  ["TerritoryGlyph", "TerritoryGlyphKind", "kind"],
];

function unionValues(typeName) {
  const match = text.match(new RegExp(`export type ${typeName}\\s*=([\\s\\S]*?);`));
  return match ? [...match[1].matchAll(/"([^"]+)"/g)].map((item) => item[1]) : [];
}

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}
const sourceFiles = walk(srcRoot).filter((file) => /\.(?:ts|tsx)$/.test(file));
const usage = new Map();
const mappedUsage = new Map();
const dynamic = [];
const directSvg = [];

function rel(file) {
  return path.relative(root, file).replaceAll("\\", "/");
}

function lineAt(source, index) {
  return source.slice(0, index).split("\n").length;
}

for (const [component, typeName, prop] of componentTypes) {
  for (const value of unionValues(typeName)) {
    usage.set(`${component}:${value}`, []);
    mappedUsage.set(`${component}:${value}`, []);
  }
}

for (const file of sourceFiles) {
  const source = fs.readFileSync(file, "utf8");
  const fileRel = rel(file);
  for (const [component, , prop] of componentTypes) {
    const literal = new RegExp(`<${component}\\b[^>]*\\b${prop}\\s*=\\s*"([^"]+)"`, "g");
    for (const match of source.matchAll(literal)) {
      const key = `${component}:${match[1]}`;
      if (!usage.has(key)) usage.set(key, []);
      usage.get(key).push(`${fileRel}:${lineAt(source, match.index)}`);
    }
  }
  for (const match of source.matchAll(/\bicon\s*:\s*"([^"]+)"/g)) {
    const key = `InstrumentGlyph:${match[1]}`;
    const site = `${fileRel}:${lineAt(source, match.index)}`;
    const bucket = mappedUsage.get(key);
    if (bucket && !bucket.includes(site)) bucket.push(site);
  }
  for (const [component, , prop] of componentTypes) {
    const any = new RegExp(`<${component}\\b[\\s\\S]*?\\/>`, "g");
    for (const match of source.matchAll(any)) {
      if (new RegExp(`\\b${prop}\\s*=\\s*"`).test(match[0])) continue;
      const dynamicSite = `${fileRel}:${lineAt(source, match.index)}`;
      for (const quoted of match[0].matchAll(/"([^"]+)"/g)) {
        const key = `${component}:${quoted[1]}`;
        const bucket = mappedUsage.get(key);
        if (bucket && !bucket.includes(dynamicSite)) bucket.push(dynamicSite);
      }
      dynamic.push({ component, file: fileRel, line: lineAt(source, match.index), jsx: match[0].replace(/\s+/g, " ").slice(0, 180) });
    }
  }

  if (file !== symbolsPath && source.includes("<svg")) {
    const lines = [...source.matchAll(/<svg\b/g)].map((match) => lineAt(source, match.index));
    directSvg.push({ file: fileRel, lines });
  }
}

function surfaceFor(file) {
  if (file.includes("/viewer/") || file.includes("/annotations/")) return "Reader / annotations";
  if (file.includes("/analysis/")) return "Analysis / map / outline";
  if (file.includes("/evidence/")) return "Evidence";
  if (file.includes("/notes/")) return "Notes / inspector";
  if (file.includes("/selection/")) return "Selection capture";
  if (file.includes("/settings/")) return "Settings";
  if (file.includes("/portrayal/")) return "Portrayal / research";
  if (file.endsWith("/App.tsx")) return "Application shell";
  return "Other";
}
const lines = [];
lines.push("# Catalyst Iconography Map", "");
lines.push("Generated by `scripts/generate-iconography-map.mjs`. Do not hand-maintain call-site counts.", "");
lines.push("## Registry summary", "");
for (const [component, typeName] of componentTypes) {
  const values = unionValues(typeName);
  const literalCount = values.reduce((sum, value) => sum + (usage.get(`${component}:${value}`)?.length ?? 0), 0);
  const mappedCount = values.reduce((sum, value) => sum + (mappedUsage.get(`${component}:${value}`)?.length ?? 0), 0);
  lines.push(`- **${component}**: ${values.length} registered variants; ${literalCount} literal call sites; ${mappedCount} mapping/runtime references.`);
}
lines.push(`- **Dynamic glyph call sites**: ${dynamic.length}.`);
lines.push(`- **Files with direct inline SVG outside CatalystSymbols**: ${directSvg.length}.`, "");
lines.push("Registry tables distinguish literal JSX calls from statically resolvable mapping/runtime references. Unresolved dynamic call sites are listed separately.", "");

for (const [component, typeName] of componentTypes) {
  lines.push(`## ${component}`, "", "| Symbol | Literal | Mapped/runtime | Surfaces | Locations |", "| --- | ---: | ---: | --- | --- |");
  for (const value of unionValues(typeName)) {
    const sites = usage.get(`${component}:${value}`) ?? [];
    const mappedSites = mappedUsage.get(`${component}:${value}`) ?? [];
    const allSites = [...sites, ...mappedSites];
    const surfaces = [...new Set(allSites.map((site) => surfaceFor(site.split(":")[0])))];
    const locations = [
      ...sites.map((site) => `\`${site}\``),
      ...mappedSites.map((site) => `\`${site}\` *(mapped/runtime)*`),
    ];
    lines.push(`| \`${value}\` | ${sites.length} | ${mappedSites.length} | ${surfaces.join(", ") || "-"} | ${locations.join("<br>") || "-"} |`);
  }
  lines.push("");
}
lines.push("## Dynamic call sites", "", "These sites choose the rendered icon from runtime state or a local mapping.", "");
lines.push("| Component | Surface | Location | Expression |", "| --- | --- | --- | --- |");
for (const item of dynamic) {
  lines.push(`| ${item.component} | ${surfaceFor(item.file)} | \`${item.file}:${item.line}\` | \`${item.jsx.replaceAll("|", "\\|")}\` |`);
}
lines.push("");

const standalone = ["CatalystMark", "AnalyticalRoleMark", "EvidenceTraceMark"];
lines.push("## Standalone semantic marks", "", "| Component | Uses | Locations |", "| --- | ---: | --- |");
for (const component of standalone) {
  const sites = [];
  for (const file of sourceFiles) {
    if (file === symbolsPath) continue;
    const source = fs.readFileSync(file, "utf8");
    for (const match of source.matchAll(new RegExp(`<${component}\\b`, "g"))) sites.push(`${rel(file)}:${lineAt(source, match.index)}`);
  }
  lines.push(`| ${component} | ${sites.length} | ${sites.map((site) => `\`${site}\``).join("<br>") || "—"} |`);
}
lines.push("");
lines.push("## Direct SVG exceptions", "", "These files draw SVG directly instead of routing every symbol through `CatalystSymbols.tsx`. Some are diagrams or portrayal primitives rather than UI icons, so each should be reviewed before consolidation.", "");
lines.push("| File | Inline SVG roots | Lines |", "| --- | ---: | --- |");
for (const item of directSvg) {
  lines.push(`| \`${item.file}\` | ${item.lines.length} | ${item.lines.join(", ")} |`);
}
lines.push("");

lines.push("## Maintenance rules", "");
lines.push("1. New reusable UI symbols belong in `src/ui/CatalystSymbols.tsx`.");
lines.push("2. Analytical meaning should be encoded by glyph geometry first; color is supplementary.");
lines.push("3. Reusing one glyph for unrelated meanings should be treated as an iconography conflict.");
lines.push("4. Direct inline SVG is acceptable for diagrams and portrayal primitives, but ordinary UI controls should use the registry.");
lines.push("5. Run `npm run icons:audit` after icon additions, removals, or major UI restructuring.", "");

fs.writeFileSync(outputPath, `${lines.join("\n")}\n`, "utf8");
console.log(`Wrote ${path.relative(root, outputPath)} with ${lines.length} lines.`);
